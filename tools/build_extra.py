def split_case(stem):
    """把病例题干切成「病例」与「问题」两段。"""
    parts = re.split(r"(?<=[。？?])", stem)
    if len(parts) >= 2 and re.search(r"(药物|治法|证|方|归经|功效|首选|应选|宜选|辨证)", parts[-1]):
        return "".join(parts[:-1]).strip(), parts[-1].strip()
    return stem, ""


def herb_lookup():
    out = {}
    for h in load_herbs():
        name = (h.get("n") or "").strip()
        if not name:
            continue
        out[name] = {
            "f": [x.strip() for x in (h.get("f") or []) if x.strip()],
            "x": (h.get("x") or "").strip(),
            "m": (h.get("m") or "").strip(),
            "c": (h.get("c") or "").strip(),
            "a": [x.strip() for x in re.split(r"[、，,；;]", h.get("a") or "") if x.strip()],
        }
    return out


def build_cases(data, H):
    out = []
    for q in data["questions"]:
        stem = q["q"]
        if not re.search(r"患者|病案|病例", stem):
            continue
        body, ask = split_case(stem)
        if not ask:
            continue
        ai = ord(q["a"][0]) - 65
        if ai >= len(q["o"]):
            continue
        ans = q["o"][ai]
        extra = ""
        h = H.get(ans)
        if h:
            extra = "功效：" + "，".join(h["f"])
            if h["x"]:
                extra += "；性味：" + h["x"]
        out.append({"q": body, "ask": ask, "a": ans, "x": extra})
    return out


def build_multi(H, limit=120):
    """按单个功效词生成多选题，干扰项优先同类药。"""
    by_term = collections.defaultdict(list)
    for name, h in H.items():
        for t in h["f"]:
            if 2 <= len(t) <= 6:
                by_term[t].append(name)
    by_cat = collections.defaultdict(list)
    for name, h in H.items():
        by_cat[h["c"]].append(name)

    out = []
    for term, names in sorted(by_term.items(), key=lambda kv: -len(kv[1])):
        if len(names) < 2:
            continue
        right = names[:3]
        cat = H[right[0]]["c"]

        def grams(s):
            return {s[i:i + 2] for i in range(len(s) - 1)}

        def subseq(a, b):
            """a 是否为 b 的子序列（允许跳字），用于识别「补肾阳/补肾助阳」这类同义缩写"""
            it = iter(b)
            return all(ch in it for ch in a)

        def too_close(name):
            for tk in H[name]["f"]:
                if tk == term:
                    return True
                if min(len(tk), len(term)) >= 3 and (subseq(tk, term) or subseq(term, tk)):
                    return True
            return False

        def shares_token(name):
            return any(set(H[name]["f"]) & set(H[r]["f"]) for r in right)

        pool = [n for n in by_cat.get(cat, []) if n not in right and term not in H[n]["f"] and not too_close(n)]
        if len(pool) < 2:
            # 同类药不够，就先找与正确答案有共同功效词的药，再退到全库抽样
            near = [n for n in H if n not in right and term not in H[n]["f"]
                    and not too_close(n) and shares_token(n)]
            pool = (near or [n for n in H if n not in right and term not in H[n]["f"] and not too_close(n)])[seed % 7:]
        wrong = pool[: 5 - len(right)]
        opts = right + wrong
        seed = len(out) * 7 + len(term)
        opts = opts[seed % len(opts):] + opts[: seed % len(opts)]   # 简单打散
        letters = [chr(65 + i) for i in range(len(opts))]
        ans = [letters[opts.index(n)] for n in right]
        out.append({
            "q": "下列药物中，具有「%s」功效的是" % term,
            "o": opts,
            "a": sorted(ans),
        })
        if len(out) >= limit:
            break
    return out


def build_essay(H, limit=200):
    out = []
    for name, h in H.items():
        if not h["f"] or not h["x"]:
            continue
        ans = "性味：" + h["x"]
        if h["m"]:
            ans += "；归经：" + h["m"]
        ans += "。功效：" + "，".join(h["f"]) + "。"
        if h["c"]:
            ans += "分类：" + h["c"].replace("·", "·") + "。"
        out.append({"q": "简述%s的性味、归经与功效。" % name, "a": ans})
        if len(out) >= limit:
            break
    return out


